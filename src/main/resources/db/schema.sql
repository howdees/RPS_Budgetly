-- Физическая схема Budgetly.
-- Скрипт соответствует сущностям JPA. Типы подобраны так, чтобы выполняться в H2 и в PostgreSQL.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(80)  NOT NULL,
    email         VARCHAR(120) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    enabled       BOOLEAN      NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE user_roles (
    user_id BIGINT      NOT NULL,
    role    VARCHAR(20) NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE budget_profiles (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT         NOT NULL,
    monthly_limit NUMERIC(14, 2) NOT NULL,
    currency      VARCHAR(8)     NOT NULL,
    goal_title    VARCHAR(255),
    CONSTRAINT uq_budget_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_budget_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE categories (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(80) NOT NULL,
    type    VARCHAR(20) NOT NULL,
    user_id BIGINT      NOT NULL,
    CONSTRAINT fk_categories_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE tags (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(40) NOT NULL,
    CONSTRAINT uq_tags_name UNIQUE (name)
);

CREATE TABLE transactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount      NUMERIC(14, 2) NOT NULL,
    operated_on DATE           NOT NULL,
    comment     VARCHAR(200),
    category_id BIGINT         NOT NULL,
    user_id     BIGINT         NOT NULL,
    CONSTRAINT fk_transactions_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_transactions_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE transaction_tags (
    transaction_id BIGINT NOT NULL,
    tag_id         BIGINT NOT NULL,
    CONSTRAINT pk_transaction_tags PRIMARY KEY (transaction_id, tag_id),
    CONSTRAINT fk_transaction_tags_tx FOREIGN KEY (transaction_id) REFERENCES transactions (id),
    CONSTRAINT fk_transaction_tags_tag FOREIGN KEY (tag_id) REFERENCES tags (id)
);

CREATE INDEX idx_categories_user ON categories (user_id);
CREATE INDEX idx_transactions_user ON transactions (user_id);
CREATE INDEX idx_transactions_category ON transactions (category_id);
CREATE INDEX idx_transactions_date ON transactions (operated_on);
